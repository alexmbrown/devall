/// Variables the generated pre-request script sets.
pub const SIGNATURE_VAR: &str = "webhookSignature";
pub const TIMESTAMP_VAR: &str = "webhookTimestamp";

/// Display name for an event: its type label, else `METHOD /path`.
pub fn event_name(e: &WebhookEvent) -> String {
    e.label.clone().unwrap_or_else(|| format!("{} {}", e.method, e.path))
}

/// Headers worth keeping when re-sending: no hop-by-hop, `Host`, or proxy/tunnel-added ones.
fn portable_headers(e: &WebhookEvent) -> Vec<(String, String)> {
    const DROP: &[&str] = &["host", "x-forwarded-for", "x-forwarded-host", "x-forwarded-proto", "x-real-ip", "cf-connecting-ip", "cf-ray", "cf-visitor", "cf-ipcountry", "cdn-loop", "x-devall-event-id", "accept-encoding"];
    without_hop_by_hop(&e.headers).into_iter().filter(|(k, _)| !DROP.contains(&k.to_ascii_lowercase().as_str()) && !k.to_ascii_lowercase().starts_with("tailscale-")).collect()
}

/// JS for a string literal.
fn js_str(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| "\"\"".into())
}

/// How the script gets the secret: `pm.secrets.get('NAME')` for `{{secret.NAME}}`, otherwise
/// `pm.variables.replaceIn(…)` (never the resolved value).
fn secret_expr(template: &str) -> String {
    let t = template.trim();
    if let Some(name) = t.strip_prefix("{{").and_then(|r| r.strip_suffix("}}")).map(str::trim).and_then(|k| k.strip_prefix("secret.")).map(str::trim)
        && !name.is_empty()
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-' || c == '.')
    {
        return format!("pm.secrets.get({})", js_str(name));
    }
    format!("pm.variables.replaceIn({})", js_str(t))
}

/// A pre-request script that recomputes the provider's signature for the request being sent and
/// stores it in `{{webhookSignature}}` (and `{{webhookTimestamp}}`). `None` when the provider has
/// no scheme.
pub fn resign_script(inbox: &InboxFile) -> Option<String> {
    let secret = secret_expr(&inbox.secret);
    let head = format!(
        "// Generated by /dev/all Webhooks: re-signs this {} webhook on every send so timestamped\n// signatures stay valid. The signature covers the raw body below; edit it freely.\nconst secret = {secret};\nconst body = pm.request.body.raw || '';\n",
        inbox.provider.label()
    );
    let ts = "const ts = String(Math.floor(Date.now() / 1000));\n";
    let set_ts = format!("pm.variables.set('{TIMESTAMP_VAR}', ts);\n");
    let body = match inbox.provider {
        ProviderKind::None => return None,
        ProviderKind::Stripe => format!("{ts}pm.variables.set('{SIGNATURE_VAR}', 't=' + ts + ',v1=' + CryptoJS.HmacSHA256(ts + '.' + body, secret).toString(CryptoJS.enc.Hex));\n"),
        ProviderKind::Github => format!("pm.variables.set('{SIGNATURE_VAR}', 'sha256=' + CryptoJS.HmacSHA256(body, secret).toString(CryptoJS.enc.Hex));\n"),
        ProviderKind::Shopify => format!("pm.variables.set('{SIGNATURE_VAR}', CryptoJS.HmacSHA256(body, secret).toString(CryptoJS.enc.Base64));\n"),
        ProviderKind::Slack => format!("{ts}{set_ts}pm.variables.set('{SIGNATURE_VAR}', 'v0=' + CryptoJS.HmacSHA256('v0:' + ts + ':' + body, secret).toString(CryptoJS.enc.Hex));\n"),
        ProviderKind::Twilio => format!(
            "// Twilio signs the full URL plus the form parameters sorted by name.\nconst url = pm.variables.replaceIn(pm.request.url.toString());\nconst dec = (s) => decodeURIComponent(s.replace(/\\+/g, ' '));\nconst params = {{}};\nif (/x-www-form-urlencoded/i.test(pm.request.headers.get('Content-Type') || '')) {{\n  for (const pair of body.split('&').filter(Boolean)) {{\n    const i = pair.indexOf('=');\n    const k = dec(i < 0 ? pair : pair.slice(0, i));\n    (params[k] = params[k] || []).push(i < 0 ? '' : dec(pair.slice(i + 1)));\n  }}\n}}\nlet data = url;\nfor (const k of Object.keys(params).sort()) for (const v of [...new Set(params[k])].sort()) data += k + v;\npm.variables.set('{SIGNATURE_VAR}', CryptoJS.HmacSHA1(data, secret).toString(CryptoJS.enc.Base64));\n"
        ),
        ProviderKind::StandardWebhooks => format!(
            "{ts}{set_ts}const id = pm.request.headers.get('webhook-id') || pm.request.headers.get('svix-id') || ('msg_' + Date.now());\nconst key = CryptoJS.enc.Base64.parse(secret.replace(/^whsec_/, ''));\npm.variables.set('{SIGNATURE_VAR}', 'v1,' + CryptoJS.HmacSHA256(id + '.' + ts + '.' + body, key).toString(CryptoJS.enc.Base64));\n"
        ),
        ProviderKind::GenericHmac => {
            let g = inbox.generic_hmac.clone().unwrap_or_default();
            let f = match g.algorithm {
                crate::model::HmacAlgorithm::Sha256 => "HmacSHA256",
                crate::model::HmacAlgorithm::Sha1 => "HmacSHA1",
                crate::model::HmacAlgorithm::Sha512 => "HmacSHA512",
            };
            let enc = if g.encoding == SignatureEncoding::Base64 { "Base64" } else { "Hex" };
            format!("pm.variables.set('{SIGNATURE_VAR}', {} + CryptoJS.{f}(body, secret).toString(CryptoJS.enc.{enc}));\n", js_str(&g.prefix))
        }
    };
    Some(format!("{head}{body}"))
}

/// Header value templates for the signature headers (`None` = keep the captured value).
fn signature_template(kind: ProviderKind, name: &str) -> Option<String> {
    let l = name.to_ascii_lowercase();
    let sig = format!("{{{{{SIGNATURE_VAR}}}}}");
    let ts = format!("{{{{{TIMESTAMP_VAR}}}}}");
    match kind {
        ProviderKind::None => None,
        ProviderKind::Github if l == "x-hub-signature" => None, // dropped instead (see below)
        ProviderKind::Slack if l == "x-slack-request-timestamp" => Some(ts),
        ProviderKind::StandardWebhooks if l.ends_with("-timestamp") => Some(ts),
        ProviderKind::StandardWebhooks if l.ends_with("-id") => None,
        _ => Some(sig),
    }
}

/// The event as an HTTP request: the original method, headers and exact body, sent to `target`
/// (default: the inbox's forward URL, else the original URL). Signature headers become
/// `{{webhookSignature}}`/`{{webhookTimestamp}}`, filled by a generated pre-request script that
/// re-signs with the inbox's secret reference. A `status < 300` test makes it a regression check.
pub fn to_request_file(e: &WebhookEvent, inbox: Option<&InboxFile>, target: Option<&str>) -> Result<HttpRequestFile, WebhookError> {
    let mut req = HttpRequestFile::new(event_name(e));
    req.method = e.method.clone();
    let target = target
        .map(str::to_string)
        .or_else(|| inbox.and_then(|f| f.forward.as_ref()).map(|fw| fw.url.clone()))
        .unwrap_or_else(|| e.url.split('?').next().unwrap_or(&e.url).to_string());
    let (base, target_query) = match target.split_once('?') {
        Some((b, q)) => (b.to_string(), q.to_string()),
        None => (target.clone(), String::new()),
    };
    req.url = base;
    let query = if target_query.is_empty() { e.query.clone() } else { target_query };
    req.params = url::form_urlencoded::parse(query.as_bytes()).map(|(k, v)| KeyValue::new(k, v)).collect();

    let kind = inbox.map(|f| f.provider).unwrap_or(ProviderKind::None);
    let sig_headers = inbox.map(|f| signature_headers(f.provider, f.generic_hmac.as_ref())).unwrap_or_default();
    let mut headers = Vec::new();
    for (k, v) in portable_headers(e) {
        let is_sig = sig_headers.iter().any(|s| s.eq_ignore_ascii_case(&k));
        if is_sig && kind == ProviderKind::Github && k.eq_ignore_ascii_case("x-hub-signature") {
            continue; // legacy SHA-1 duplicate of X-Hub-Signature-256
        }
        match (is_sig, signature_template(kind, &k)) {
            (true, Some(t)) => {
                let mut kv = KeyValue::new(k, t);
                kv.description = Some("Re-signed by the pre-request script on every send".into());
                headers.push(kv);
            }
            _ => headers.push(KeyValue::new(k, v)),
        }
    }
    req.headers = headers;

    let ct = header(&e.headers, "content-type").map(str::to_string);
    req.body = match std::str::from_utf8(&e.body) {
        _ if e.body.is_empty() => Body::None,
        // Bodies stay byte-exact (no pretty-printing): signatures cover the raw bytes. Form
        // bodies stay raw text too, so field order and encoding are kept.
        Ok(t) if is_json_content_type(ct.as_deref()) => Body::Json { content: t.to_string() },
        Ok(t) => Body::Text { content: t.to_string(), content_type: ct.clone() },
        Err(_) => return Err(WebhookError::Invalid("binary bodies can't be saved as a request yet — save a fixture instead".into())),
    };
    if let Some(f) = inbox
        && let Some(script) = resign_script(f)
    {
        req.scripts = Some(Scripts { pre_request: script, post_response: String::new() });
    }
    req.tests = vec![Assertion { target: AssertTarget::Status, op: AssertOp::Lt, value: Some("300".into()), enabled: true }];
    let mut docs = format!("Captured by /dev/all Webhooks{} on {}.", inbox.map(|f| format!(" (inbox **{}**)", f.name)).unwrap_or_default(), fmt_time(e.received_at));
    if let Some(f) = inbox.filter(|f| f.provider != ProviderKind::None) {
        docs.push_str(&format!(
            "\n\nThe {} signature headers use `{{{{{SIGNATURE_VAR}}}}}`, computed by the pre-request script from `{}` for the body being sent — edit the body freely. You can also replay the original event with re-signing from the Webhooks page.",
            f.provider.label(),
            f.secret.trim()
        ));
    }
    req.docs = Some(docs);
    Ok(req)
}

fn fmt_time(ms: i64) -> String {
    chrono::DateTime::from_timestamp_millis(ms).map(|d| d.format("%Y-%m-%d %H:%M:%S UTC").to_string()).unwrap_or_default()
}

/// Saves the event as `http/<folder>/<slug>.req.yaml`; returns its path relative to `http/`.
pub fn save_as_request(project: &devall_core::Project, folder: &str, e: &WebhookEvent, inbox: Option<&InboxFile>, target: Option<&str>) -> Result<String, WebhookError> {
    let req = to_request_file(e, inbox, target)?;
    Ok(project.create_request(folder, req)?)
}

/// cURL for an outbound request (bash quoting).
pub fn curl_for(req: &OutboundRequest) -> String {
    let prepared = devall_http::PreparedRequest {
        method: req.method.clone(),
        url: req.url.clone(),
        headers: req.headers.clone(),
        body: if req.body.is_empty() { devall_http::PreparedBody::None } else { devall_http::PreparedBody::Bytes(req.body.clone()) },
        timeout_ms: 0,
        follow_redirects: false,
        verify_tls: true,
        proxy: None,
        client_cert: None,
        digest: None,
        ntlm: None,
    };
    devall_http::to_curl(&prepared)
}

/// `webhooks/fixtures/<slug>.json`: the payload for tests (signature headers listed, not kept).
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Fixture {
    pub version: u32,
    pub name: String,
    pub inbox: Option<String>,
    pub provider: Option<ProviderKind>,
    pub method: String,
    pub path: String,
    #[serde(skip_serializing_if = "String::is_empty")]
    pub query: String,
    pub headers: Vec<(String, String)>,
    /// Headers the provider signs with; sign the fixture again when sending it.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub signature_headers: Vec<String>,
    /// `json` (body is the parsed payload), `text` or `base64`.
    pub body_encoding: &'static str,
    pub body: serde_json::Value,
}

pub fn to_fixture(e: &WebhookEvent, inbox: Option<&InboxFile>) -> Fixture {
    let sig = inbox.map(|f| signature_headers(f.provider, f.generic_hmac.as_ref())).unwrap_or_default();
    let mut headers: Vec<(String, String)> = portable_headers(e).into_iter().filter(|(k, _)| !sig.iter().any(|s| s.eq_ignore_ascii_case(k))).collect();
    for (k, v) in headers.iter_mut() {
        if k.eq_ignore_ascii_case("authorization") || k.eq_ignore_ascii_case("cookie") {
            *v = "••••••".into();
        }
    }
    let present: Vec<String> = sig.into_iter().filter(|s| header(&e.headers, s).is_some()).collect();
    let ct = header(&e.headers, "content-type");
    let (enc, body) = match std::str::from_utf8(&e.body) {
        Ok(t) if is_json_content_type(ct) => match serde_json::from_str::<serde_json::Value>(t) {
            Ok(v) => ("json", v),
            Err(_) => ("text", serde_json::Value::String(t.to_string())),
        },
        Ok(t) => ("text", serde_json::Value::String(t.to_string())),
        Err(_) => ("base64", serde_json::Value::String(base64::engine::general_purpose::STANDARD.encode(&e.body))),
    };
    Fixture {
        version: 1,
        name: event_name(e),
        inbox: e.inbox.clone(),
        provider: inbox.map(|f| f.provider).filter(|p| *p != ProviderKind::None),
        method: e.method.clone(),
        path: e.path.clone(),
        query: e.query.clone(),
        headers,
        signature_headers: present,
        body_encoding: enc,
        body,
    }
}

/// Writes `webhooks/fixtures/<slug>.json`; returns the path relative to the project root.
pub fn save_fixture(root: &Path, e: &WebhookEvent, inbox: Option<&InboxFile>) -> Result<String, WebhookError> {
    let fx = to_fixture(e, inbox);
    let dir = root.join(WEBHOOKS_DIR).join(FIXTURES_DIR);
    std::fs::create_dir_all(&dir).map_err(|err| WebhookError::Io(format!("{}: {err}", dir.display())))?;
    let file = unique_name(&dir, &slugify(&fx.name), ".json");
    let mut json = serde_json::to_string_pretty(&fx).map_err(|err| WebhookError::Invalid(err.to_string()))?;
    json.push('\n');
    atomic_write(&dir.join(&file), json.as_bytes())?;
    Ok(format!("{WEBHOOKS_DIR}/{FIXTURES_DIR}/{file}"))
}

