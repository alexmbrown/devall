/// The main window (`"create": false` in tauri.conf.json) with a title bar per platform: on
/// Windows the app's top bar is the title bar (no system frame; caption buttons drawn by
/// `WindowControls`, DWM shadow and resize borders kept), on macOS the traffic lights sit on the top
/// bar (overlay title bar), and Linux keeps the system frame.
fn build_main_window(app: &tauri::App) -> Result<(), Box<dyn std::error::Error>> {
    let cfg = app.config().app.windows.iter().find(|w| w.label == "main").cloned().ok_or("tauri.conf.json has no \"main\" window")?;
    let builder = tauri::WebviewWindowBuilder::from_config(app.handle(), &cfg)?;
    #[cfg(windows)]
    let builder = builder.decorations(false);
    // y is about the lights' vertical centre: 22 centres them on the 44px top bar (tokens.css --topbar-h).
    #[cfg(target_os = "macos")]
    let builder = builder.title_bar_style(tauri::TitleBarStyle::Overlay).hidden_title(true).traffic_light_position(tauri::LogicalPosition::new(16.0, 22.0));
    builder.build()?;
    Ok(())
}

