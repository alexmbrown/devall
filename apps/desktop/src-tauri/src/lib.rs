            build_main_window(app)?;
            let config_dir = app.path().app_config_dir()?;
            let data_dir = app.path().app_data_dir()?;
            app.manage(modules::notes::NotesState::new(data_dir.clone()));
            modules::notes::start_reminders(app.handle());
            app.manage(modules::watch::WatchState::default());
            app.manage(modules::git::GitWatchState::default());
            app.manage(modules::git_review::GitGraphState::default());
            // Per-project history and caches live under this folder (shared with the CLI).
            devall_core::local::set_app_data_dir(data_dir.clone());
            app.manage(modules::history::HistoryState::default());
            app.manage(modules::load::LoadState::new());
            app.manage(modules::notebooks::NotebookState::new(data_dir.clone()));
            app.manage(modules::ai::AiState::new(data_dir.clone()));
            app.manage(modules::proxy::ProxyState::new(data_dir.clone()));
            app.manage(modules::mock::MockState::default());
            app.manage(modules::plugins::PluginState::new(data_dir.clone()));
            app.manage(modules::proto::ProtoState::default());
            // Hosted webhook inbox → the project's webhook hub (at-least-once; ingest dedupes by id).
            let relay = modules::relay::RelayState::new(config_dir.clone());
            let handle = app.handle().clone();
            relay.set_inbox_sink(std::sync::Arc::new(move |root: String, ev: devall_relay::InboxEvent| {
                let handle = handle.clone();
                Box::pin(async move {
                    let hub = handle.state::<modules::webhooks::WebhookState>().hub(&root)?;
                    let incoming = devall_webhooks::IncomingEvent {
                        method: ev.method.clone(),
                        url: ev.url.clone(),
                        path: ev.path.clone(),
                        headers: ev.headers.clone(),
                        body: ev.body().map_err(|e| e.to_string())?,
                        received_at: ev.received_at_ms().unwrap_or(0),
                        remote_addr: ev.source_ip.clone(),
                        public_url: Some(ev.url.clone()),
                        external_id: Some(ev.id.clone()),
                        source: devall_webhooks::EventSource::Relay,
                        ..Default::default()
                    };
                    hub.ingest(incoming).await.map(|_| ()).map_err(|e| e.to_string())
                })
            }));
            app.manage(relay);
            app.manage(modules::logs::LogsState::default());
            app.manage(modules::infra::InfraState::new());
            app.manage(modules::db::DbState::new());
            app.manage(modules::webhooks::WebhookState::new(app.handle().clone()));
